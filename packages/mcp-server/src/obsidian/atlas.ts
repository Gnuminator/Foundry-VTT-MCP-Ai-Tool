// Quests and places from the mirror notes
// ---------------------------------------------------------------------------

const CARD_W = 300;
const CARD_H = 180;
const GAP = 40;
const BODY_MAX_BYTES = 65_536;
const MAX_CARDS = 400;

function shortId(prefix: string, uuid: string): string {
  return `${prefix}${createHash('sha256').update(uuid).digest('hex').slice(0, 12)}`;
}

function cardId(uuid: string): string {
  return shortId(`${ATLAS_ID_PREFIX}n-`, uuid);
}

function fileNode(
  worldId: string,
  note: ScannedNote,
  x: number,
  y: number,
  color?: string
): CanvasNode {
  const node: CanvasNode = {
    id: cardId(note.uuid),
    type: 'file',
    file: `Campaigns/${worldId}/${note.path}`,
    x,
    y,
    width: CARD_W,
    height: CARD_H,
  };
  if (color) node.color = color;
  return node;
}

function edge(fromId: string, toId: string, fromSide: string, toSide: string): CanvasEdge {
  return {
    id: `${ATLAS_ID_PREFIX}e-${fromId.slice(ATLAS_ID_PREFIX.length)}-${toId.slice(ATLAS_ID_PREFIX.length)}`,
    fromNode: fromId,
    fromSide,
    toNode: toId,
    toSide,
  };
}

const byName = (a: ScannedNote, b: ScannedNote): number =>
  (a.name ?? a.path).localeCompare(b.name ?? b.path) || (a.uuid < b.uuid ? -1 : 1);

/** Markdown link targets in a body (`](target)`), without fragments, decoded. */
function linkTargets(body: string): string[] {
  const out: string[] = [];
  for (const match of body.matchAll(/\]\(([^)\s]+)\)/g)) {
    let target = match[1] ?? '';
    if (/^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
    target = target.split('#')[0] ?? '';
    if (!target.endsWith('.md')) continue;
    try {
      out.push(decodeURIComponent(target));
    } catch {
      out.push(target);
    }
  }
  return out;
}

async function readBody(root: string, relPath: string): Promise<string> {
  const handle = await fsp.open(path.join(root, relPath), 'r').catch(() => null);
  if (!handle) return '';
  try {
    const buffer = Buffer.alloc(BODY_MAX_BYTES);
    const { bytesRead } = await handle.read(buffer, 0, BODY_MAX_BYTES, 0);
    return buffer.subarray(0, bytesRead).toString('utf8');
  } finally {
    await handle.close();
  }
}

/** The top-level mirror note a note path stands for: itself, or the journal of a page note. */
function indexByPath(scan: MirrorScan): Map<string, ScannedNote> {
  const index = new Map<string, ScannedNote>();
  for (const note of scan.mirror.values()) index.set(note.path.toLowerCase(), note);
  for (const note of scan.pages.values()) {
    const journal = note.journalUuid ? scan.mirror.get(note.journalUuid) : undefined;
    if (journal) index.set(note.path.toLowerCase(), journal);
  }
  return index;
}

/** The mirror notes that `note` (and its page notes, for a journal) link to, other than itself. */
async function linkedNotes(
  root: string,
  scan: MirrorScan,
  index: Map<string, ScannedNote>,
  note: ScannedNote
): Promise<ScannedNote[]> {
  const sources = [note.path];
  if (note.type === 'journal') {
    for (const page of scan.pages.values())
      if (page.journalUuid === note.uuid) sources.push(page.path);
  }
  const found = new Map<string, ScannedNote>();
  for (const source of sources) {
    const body = await readBody(root, source);
    for (const target of linkTargets(body)) {
      const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(source), target));
      const hit = index.get(resolved.toLowerCase());
      if (hit && hit.uuid !== note.uuid) found.set(hit.uuid, hit);
    }
  }
  return [...found.values()].sort(byName);
}

const isQuest = (note: ScannedNote): boolean =>
  note.type === 'journal' && /quest/i.test(note.folder ?? '');

function finish(nodes: CanvasNode[], edges: CanvasEdge[]): string {
  nodes.push({
    id: 'generated',
    type: 'text',
    text: '',
    x: -300,
    y: -260,
    width: 900,
    height: 110,
  });
  return withCanvasHash({ nodes, edges }, ATLAS_BANNER);
}

/** `Quests.canvas`: quest journals in a left column, the notes they link to on the right. */
export async function renderQuestsCanvas(
  worldId: string,
  root: string,
  scan: MirrorScan
): Promise<string> {
  const index = indexByPath(scan);
  const quests = [...scan.mirror.values()].filter(isQuest).sort(byName).slice(0, MAX_CARDS);
  const nodes: CanvasNode[] = [];
  const edges: CanvasEdge[] = [];
  const questIds = new Set(quests.map(quest => quest.uuid));
  const placed = new Set<string>();
  let right = 0;
  quests.forEach((quest, row) => {
    nodes.push(fileNode(worldId, quest, 0, row * (CARD_H + GAP), '1'));
  });
  for (const quest of quests) {
    for (const target of await linkedNotes(root, scan, index, quest)) {
      if (isQuest(target)) {
        // Another quest: an arrow to its card, no second card.
        if (questIds.has(target.uuid))
          edges.push(edge(cardId(quest.uuid), cardId(target.uuid), 'right', 'left'));
        continue;
      }
      if (!placed.has(target.uuid)) {
        placed.add(target.uuid);
        nodes.push(fileNode(worldId, target, CARD_W * 2, right * (CARD_H + GAP)));
        right++;
      }
      edges.push(edge(cardId(quest.uuid), cardId(target.uuid), 'right', 'left'));
    }
  }
  return finish(nodes, edges);
}

/** `Places.canvas`: scene notes in one group per Foundry folder, arrows for links between scenes. */
export async function renderPlacesCanvas(
  worldId: string,
  root: string,
  scan: MirrorScan
): Promise<string> {
  const index = indexByPath(scan);
  const scenes = [...scan.mirror.values()]
    .filter(note => note.type === 'scene')
    .sort(byName)
    .slice(0, MAX_CARDS);
  const groups = new Map<string, ScannedNote[]>();
  for (const scene of scenes) {
    const key = scene.folder ?? '';
    const list = groups.get(key) ?? [];
    list.push(scene);
    groups.set(key, list);
  }
  const nodes: CanvasNode[] = [];
  const edges: CanvasEdge[] = [];
  const COLS = 3;
  const GROUP_COLS = 2;
  const groupW = COLS * (CARD_W + GAP) + GAP;
  const sorted = [...groups.entries()].sort(([a], [b]) => a.localeCompare(b));
  let groupRowTop = 0;
  let rowHeight = 0;
  sorted.forEach(([folder, list], i) => {
    const col = i % GROUP_COLS;
    if (col === 0 && i > 0) {
      groupRowTop += rowHeight + GAP * 2;
      rowHeight = 0;
    }
    const rows = Math.ceil(list.length / COLS);
    const height = rows * (CARD_H + GAP) + GAP + 40;
    rowHeight = Math.max(rowHeight, height);
    const gx = col * (groupW + GAP * 2);
    nodes.push({
      id: shortId(`${ATLAS_ID_PREFIX}g-`, folder || '(none)'),
      type: 'group',
      label: folder || 'No folder',
      x: gx,
      y: groupRowTop,
      width: groupW,
      height,
    });
    list.forEach((scene, k) => {
      nodes.push(
        fileNode(
          worldId,
          scene,
          gx + GAP + (k % COLS) * (CARD_W + GAP),
          groupRowTop + 40 + GAP + Math.floor(k / COLS) * (CARD_H + GAP)
        )
      );
    });
  });
  const shown = new Set(scenes.map(scene => scene.uuid));
  for (const scene of scenes) {
    for (const target of await linkedNotes(root, scan, index, scene)) {
      if (target.type === 'scene' && shown.has(target.uuid)) {
        edges.push(edge(cardId(scene.uuid), cardId(target.uuid), 'right', 'left'));
      }
    }
  }
  return finish(nodes, edges);
}


/**
 * The Campaign Atlas (I-185): three Obsidian Canvas files in the GM vault, `Tarokka/Spread.canvas`
 * (written by `renderSpreadCanvas`), `Atlas/Quests.canvas` and `Atlas/Places.canvas`. Quests and
 * places are built from the mirror notes already on disk (`AI Tool/Foundry/...`): a card is a
 * `file` node pointing at a mirror note, an edge is a link between two of those notes.
 *
 * Hand-moved cards stay put: {@link mergeCanvas} copies the position and size of every generated
 * card (matched by id) from the canvas already on disk, and keeps cards and edges the GM added
 * (ids the tool does not make). Ownership is the marker node alone ({@link checkAtlasOwnership});
 * a canvas whose marker node the GM deleted is theirs and is left alone.
 *
 * GM vault only: the export that calls this never writes to a player vault.
 */
import { createHash } from 'crypto';
import { promises as fsp } from 'fs';
import * as path from 'path';

import { errorCode } from './note-writer.js';
import {
  GENERATED_BY,
  withCanvasHash,
  type CanvasMarkerDoc,
  type OwnershipResult,
} from './ownership.js';
import type { MirrorScan } from './mirror-scan.js';
import type { ScannedNote } from './mirror-common.js';

export const QUESTS_CANVAS_PATH = 'AI Tool/Atlas/Quests.canvas';
export const PLACES_CANVAS_PATH = 'AI Tool/Atlas/Places.canvas';

/** The marker node's note: unlike a note, a canvas keeps the GM's card positions. */
const ATLAS_BANNER =
  '> [!info] Generated by the Foundry AI Tool\n' +
  '> Cards and links are rebuilt from the bridge vault on every export. Move cards freely: ' +
  'their positions are kept. Add your own cards and arrows too. Delete this card to take the canvas over.';

/** The ids of generated cards are `atlas-...`; Spread cards use their position names. */
const ATLAS_ID_PREFIX = 'atlas-';

type CanvasNode = { id: string; [key: string]: unknown };
type CanvasEdge = { id: string; [key: string]: unknown };
interface CanvasDoc extends CanvasMarkerDoc {
  nodes: CanvasNode[];
  edges?: CanvasEdge[];
}

const GEOMETRY = ['x', 'y', 'width', 'height'] as const;

function parseDoc(text: string | null): CanvasDoc | null {
  if (text === null) return null;
  try {
    const parsed = JSON.parse(text) as Partial<CanvasDoc> | null;
    return parsed && Array.isArray(parsed.nodes) ? (parsed as CanvasDoc) : null;
  } catch {
    return null;
  }
}

/**
 * The canvas text to write: `nextText` (a freshly rendered canvas) with the position and size of
 * each card taken from `existingText` (same id), plus the cards and arrows the GM added
 * (`isGeneratedId` false). With no existing canvas this is `nextText` itself.
 */
export function mergeCanvas(
  nextText: string,
  existingText: string | null,
  isGeneratedId: (id: string) => boolean,
  /** Also keep the colour of a card and the label and colour of an arrow (Atlas canvases; the
   * Spread's colour says whether a card is revealed, so it is always rebuilt). */
  keepStyle = false
): string {
  const next = parseDoc(nextText);
  const existing = parseDoc(existingText);
  if (!next || !existing) return nextText;
  const old = new Map<string, CanvasNode>();
  for (const node of existing.nodes)
    if (node && typeof node.id === 'string') old.set(node.id, node);
  const nodes = next.nodes.map(node => {
    const before = old.get(node.id);
    if (!before || node.id === 'generated') return node;
    const merged = { ...node };
    for (const key of GEOMETRY) if (typeof before[key] === 'number') merged[key] = before[key];
    if (keepStyle && typeof before.color === 'string') merged.color = before.color;
    return merged;
  });
  const taken = new Set(nodes.map(node => node.id));
  for (const node of existing.nodes) {
    if (!node || typeof node.id !== 'string' || node.id === 'generated') continue;
    if (isGeneratedId(node.id) || taken.has(node.id)) continue;
    nodes.push(node);
    taken.add(node.id);
  }
  const oldEdges = new Map<string, CanvasEdge>();
  for (const edge of existing.edges ?? [])
    if (edge && typeof edge.id === 'string') oldEdges.set(edge.id, edge);
  const edges = (next.edges ?? []).map(edge => {
    const before = oldEdges.get(edge.id);
    if (!keepStyle || !before) return edge;
    const merged = { ...edge };
    if (typeof before.label === 'string') merged.label = before.label;
    if (typeof before.color === 'string') merged.color = before.color;
    return merged;
  });
  const takenEdges = new Set(edges.map(edge => edge.id));
  for (const edge of oldEdges.values()) {
    if (isGeneratedId(edge.id) || takenEdges.has(edge.id)) continue;
    // An arrow of the GM's whose card is gone would dangle.
    if (!taken.has(String(edge.fromNode)) || !taken.has(String(edge.toNode))) continue;
    edges.push(edge);
    takenEdges.add(edge.id);
  }
  return withCanvasHash({ ...next, nodes, edges }, ATLAS_BANNER);
}

/** Ours while the marker node is there: edits to positions and extra cards are merged, not refused. */
export function checkAtlasOwnership(existingText: string): OwnershipResult {
  const doc = parseDoc(existingText);
  const marker = doc?.nodes.find(node => node?.id === 'generated');
  const text = typeof marker?.text === 'string' ? marker.text : '';
  return text.includes(`generated_by: ${GENERATED_BY}`)
    ? { owned: true, legacy: false }
    : { owned: false, reason: 'not written by the AI Tool' };
}

/** The existing canvas text, or null when the file is not there. */
export async function readExisting(root: string, relPath: string): Promise<string | null> {
  return fsp.readFile(path.join(root, relPath), 'utf8').catch(error => {
    if (errorCode(error) === 'ENOENT') return null;
    throw error;
  });
}


const CANVAS_NODE_W = 320;
const CANVAS_NODE_H = 220;
/** Cross layout: holySymbol top, tome left, strahdLocation centre, sunsword right, ally bottom. */
const CANVAS_LAYOUT: Record<string, { x: number; y: number }> = {
  holySymbol: { x: 0, y: -300 },
  tome: { x: -460, y: 0 },
  strahdLocation: { x: 0, y: 0 },
  sunsword: { x: 460, y: 0 },
  ally: { x: 0, y: 300 },
};

function canvasNode(
  id: string,
  text: string,
  x: number,
  y: number,
  width: number,
  height: number,
  color?: string
): { id: string; [key: string]: unknown } {
  const node: { id: string; [key: string]: unknown } = {
    id,
    type: 'text',
    text,
    x,
    y,
    width,
    height,
  };
  if (color !== undefined) node.color = color;
  return node;
}

/** `AI Tool/Tarokka/Spread.canvas` (JSON Canvas 1.0): one text node per
 * position laid out as a cross, plus the ownership marker node. */
export function renderSpreadCanvas(
  reading: TarokkaReadingData | null,
  cardNames: Record<string, string> = {}
): string {
  const nodes: Array<{ id: string; [key: string]: unknown }> = [];
  if (reading) {
    for (const [key, label] of POSITIONS) {
      const p = reading.positions[key];
      const pos = CANVAS_LAYOUT[key];
      if (!p || !pos) continue;
      const name = cardNames[p.cardId] ?? p.cardName;
      const text = [
        `## ${label}`,
        '',
        callout('danger', 'Card (GM secret)', [
          `**${name}** (\`${p.cardId}\`)`,
          ...(p.gmNote ? ['', `GM note: ${p.gmNote}`] : []),
        ]),
        '',
        `Revealed: ${p.revealed ? 'yes' : 'no'}`,
      ].join('\n');
      nodes.push(
        canvasNode(
          key,
          text,
          pos.x,
          pos.y,
          CANVAS_NODE_W,
          CANVAS_NODE_H,
          p.revealed ? '4' : undefined
        )
      );
    }
  } else {
    nodes.push(canvasNode('no-reading', 'No reading yet', 0, 0, CANVAS_NODE_W, CANVAS_NODE_H));
  }
  nodes.push(canvasNode('generated', '', -300, -620, 900, 110));
  const doc: CanvasMarkerDoc = { nodes, edges: [] };
  return withCanvasHash(doc, GENERATED_BANNER);
}


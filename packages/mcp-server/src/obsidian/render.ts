export interface SessionEvent {
  id?: string;
  timestamp?: string;
  eventType?: string;
  actorName?: string | null;
  description?: string;
  details?: Record<string, unknown> | null;
}

/** One note per day of the backend's session log (`sessions/<date>.jsonl`). */
export function renderSessionNote(worldId: string, date: string, events: SessionEvent[]): string {
  const sorted = [...events].sort((a, b) =>
    String(a.timestamp ?? '').localeCompare(String(b.timestamp ?? ''))
  );
  const types = [...new Set(sorted.map(e => e.eventType ?? 'event'))].sort();
  const actors = [
    ...new Set(sorted.map(e => e.actorName).filter((n): n is string => Boolean(n))),
  ].sort();
  const changeIds = sorted
    .map(e => e.details?.changeId)
    .filter((id): id is string => typeof id === 'string');
  const props = frontmatter({
    type: 'session-log',
    world: worldId,
    date,
    events: sorted.length,
    first_event: shortTime(sorted[0]?.timestamp),
    last_event: shortTime(sorted[sorted.length - 1]?.timestamp),
    event_types: types,
    actors,
    changes: changeIds.length,
    generated: true,
  });
  const rows = sorted.map(e => {
    const change = typeof e.details?.changeId === 'string' ? ` (${e.details.changeId})` : '';
    return `| ${cell(shortTime(e.timestamp).slice(11))} | ${cell(e.eventType)} | ${cell(e.actorName)} | ${cell(`${e.description ?? ''}${change}`)} |`;
  });
  return [
    props,
    `# Session log ${date}`,
    '',
    GENERATED_BANNER,
    '',
    `${sorted.length} event(s) recorded by the bridge (times in UTC). Changes link to [the change log](../Changes/${date.slice(0, 7)}.md).`,
    '',
    '| Time | Type | Who | What |',
    '| --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------
// Change log (audit)
// ---------------------------------------------------------------------------

export interface ChangeEntry {
  changeId: string;
  feature: string;
  summary: string;
  risk: string;
  target: string;
  mode: 'apply' | 'undo';
  appliedAt: string;
  diff: string[];
  undoOf?: string;
  undoneBy?: string;
  undoneAt?: string;
}

/** One note per month of applied and undone guarded changes, newest first. */
export function renderChangesNote(worldId: string, month: string, entries: ChangeEntry[]): string {
  const sorted = [...entries].sort((a, b) => b.appliedAt.localeCompare(a.appliedAt));
  const props = frontmatter({
    type: 'change-log',
    world: worldId,
    month,
    changes: sorted.length,
    applied: sorted.filter(e => e.mode === 'apply').length,
    undone: sorted.filter(e => e.mode === 'apply' && e.undoneBy).length,
    features: [...new Set(sorted.map(e => e.feature))].sort(),
    generated: true,
  });
  const blocks = sorted.map(e => {
    const state =
      e.mode === 'undo'
        ? `undo of \`${e.undoOf ?? '?'}\``
        : e.undoneBy
          ? `undone by \`${e.undoneBy}\` at ${shortTime(e.undoneAt)}`
          : 'applied';
    return [
      `### ${shortTime(e.appliedAt)} · ${e.summary}`,
      '',
      `- Change \`${e.changeId}\` · feature **${e.feature}** · ${e.mode} · risk ${e.risk} · written to ${e.target}`,
      `- State: ${state}`,
      '',
      callout(
        'note',
        `Diff (${e.diff.length} line(s), GM only)`,
        e.diff.map(d => `- ${d}`)
      ),
      '',
    ].join('\n');
  });
  return [
    props,
    `# Changes ${month}`,
    '',
    GENERATED_BANNER,
    '',
    'Every change the AI Tool applied or undid through guarded writes (times in UTC). Undo from the co-GM dashboard (Recent Changes).',
    '',
    ...blocks,
  ].join('\n');
}


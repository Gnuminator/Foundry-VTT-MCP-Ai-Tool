export interface TarokkaPositionData {
  cardId: string;
  cardName: string;
  gmNote: string | null;
  revealed: boolean;
  revealPageUuid?: string;
}

export interface TarokkaReadingData {
  readingId: string;
  source: string;
  readAt: string;
  positions: Record<string, TarokkaPositionData>;
}

export interface TarokkaLinks {
  journalPageUuid?: string;
  sceneUuid?: string;
  actorUuid?: string;
}

const POSITIONS: Array<[string, string]> = [
  ['tome', 'Tome'],
  ['holySymbol', 'Holy symbol'],
  ['sunsword', 'Sunsword'],
  ['ally', 'Ally'],
  ['strahdLocation', "Strahd's location"],
];

/** The current reading (GM only): cards hidden in collapsed callouts, links and reveals. */
export function renderTarokkaNote(
  worldId: string,
  reading: TarokkaReadingData | null,
  options: {
    links?: Partial<Record<string, Record<string, TarokkaLinks>>>;
    cardNames?: Record<string, string>;
    archived?: string[];
    revealJournalUuid?: string | null;
  } = {}
): string {
  if (!reading) {
    return [
      frontmatter({ type: 'tarokka-reading', world: worldId, reading_id: null, generated: true }),
      '# Tarokka reading',
      '',
      GENERATED_BANNER,
      '',
      'No reading is stored yet. Deal or import one from the co-GM dashboard (🃏 Tarokka).',
      '',
    ].join('\n');
  }
  const sections: string[] = [];
  let revealed = 0;
  let linked = 0;
  for (const [key, label] of POSITIONS) {
    const p = reading.positions[key];
    if (!p) continue;
    const name = options.cardNames?.[p.cardId] ?? p.cardName;
    const links = options.links?.[key]?.[p.cardId] ?? {};
    const linkLines = [
      links.journalPageUuid ? `- Journal page: \`${links.journalPageUuid}\`` : null,
      links.sceneUuid ? `- Scene: \`${links.sceneUuid}\`` : null,
      links.actorUuid ? `- Actor: \`${links.actorUuid}\`` : null,
    ].filter((l): l is string => l !== null);
    if (linkLines.length) linked += 1;
    if (p.revealed) revealed += 1;
    sections.push(
      [
        `## ${label}`,
        '',
        callout('danger', 'Card (GM secret)', [
          `**${name}** (\`${p.cardId}\`)`,
          ...(p.gmNote ? ['', `GM note: ${p.gmNote}`] : []),
        ]),
        '',
        `- Revealed to players: ${p.revealed ? `yes (page \`${p.revealPageUuid ?? '?'}\`)` : 'no'}`,
        ...(linkLines.length ? linkLines : ['- Not linked yet (link it in the dashboard)']),
        '',
      ].join('\n')
    );
  }
  return [
    frontmatter({
      type: 'tarokka-reading',
      world: worldId,
      reading_id: reading.readingId,
      source: reading.source,
      read_at: shortTime(reading.readAt),
      revealed_count: revealed,
      linked_count: linked,
      archived_readings: options.archived?.length ?? 0,
      reveal_journal: options.revealJournalUuid ?? null,
      generated: true,
    }),
    '# Tarokka reading',
    '',
    GENERATED_BANNER,
    '',
    'GM only. The reading lives in the bridge vault, never in Foundry world data. Card names are in collapsed callouts so they do not show at a glance.',
    '',
    ...sections,
    ...(options.archived?.length
      ? ['## Archive', '', ...options.archived.map(id => `- \`${id}\``), '']
      : []),
  ].join('\n');
}


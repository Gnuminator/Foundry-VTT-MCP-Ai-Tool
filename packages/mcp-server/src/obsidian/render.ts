export interface SessionGroupInput {
  events: SessionEvent[];
  startedBy: StartedBy;
  endedBy: EndedBy;
}

/** One note per play session: `AI Tool/Sessions/<date> S<NN>.md`. The
 * timeline table still comes from the session-log events alone (`group`);
 * `stats` (from `stats/build.ts`, contract 5) supplies the session's number,
 * label and bounds plus the O3 play-log properties and the Stats section, so
 * the note and `get-play-stats` always agree. */
export function renderSessionNote(
  worldId: string,
  group: SessionGroupInput,
  stats: SessionStats,
  /** Links to this day's recorded session notes in Foundry (D-087), as list lines. */
  sessionNotes: readonly string[] = []
): string {
  const sorted = [...group.events].sort((a, b) => eventTimeMs(a) - eventTimeMs(b));
  const types = [...new Set(sorted.map(e => e.eventType ?? 'event'))].sort();
  const actors = [
    ...new Set(sorted.map(e => e.actorName).filter((n): n is string => Boolean(n))),
  ].sort();
  // Changes/ notes are named by the UTC month a change was applied; the event
  // that logged a change carries its id at (about) that time.
  const changeMonths = new Map<string, string>();
  for (const e of sorted) {
    const id = e.details?.changeId;
    if (typeof id === 'string' && !changeMonths.has(id)) {
      changeMonths.set(id, new Date(eventTimeMs(e)).toISOString().slice(0, 7));
    }
  }
  const uniqueChangeIds = [...changeMonths.keys()];
  const scenes = [
    ...new Set(
      sorted
        .filter(e => e.eventType === 'scene-change')
        .map(e => (typeof e.details?.sceneName === 'string' ? e.details.sceneName : null))
        .filter((n): n is string => n !== null)
    ),
  ].sort();

  const props = generatedProps(
    'session',
    worldId,
    {
      session_number: stats.number,
      date: stats.date,
      started_at: stats.startedAt,
      ended_at: stats.endedAt,
      duration_min: stats.durationMin,
      started_by: group.startedBy,
      ended_by: group.endedBy,
      events: sorted.length,
      event_types: types,
      actors,
      changes: uniqueChangeIds.length,
      scenes,
      // O3 (docs/design/OBSIDIAN-PLAN.md section 8): play-log derived stats, built by
      // stats/build.ts over the same session (contract 5).
      play_records: stats.playRecords,
      combats: stats.combats.length,
      combat_rounds: stats.combatRounds,
      party_damage_dealt: stats.partyDamageDealt,
      party_damage_taken: stats.partyDamageTaken,
      party_healing: stats.partyHealing,
      pc_downs: stats.pcDowns,
      npc_kills: stats.npcKills,
      rolls: stats.rolls,
      crits: stats.crits,
      fumbles: stats.fumbles,
      spells_cast: stats.spellsCast,
      spell_slots_spent: stats.spellSlotsSpent,
      gm_changes: stats.gmChanges,
    },
    stats.endedAt
  );

  const rows = sorted.map(e => {
    const change = typeof e.details?.changeId === 'string' ? ` (${e.details.changeId})` : '';
    const time = e.timestamp ?? new Date(eventTimeMs(e)).toISOString();
    // Rolls: the GM's full breakdown (dice, each bonus, target and outcome).
    const breakdown = e.details?.breakdown;
    const what = typeof breakdown === 'string' && breakdown ? breakdown : (e.description ?? '');
    return `| ${cell(shortTime(time).slice(11))} | ${cell(e.eventType)} | ${cell(e.actorName)} | ${cell(`${what}${change}`)} |`;
  });
  const changeLinks = uniqueChangeIds.map(
    id => `- [${id}](../Changes/${changeMonths.get(id) ?? ''}.md#^${id})`
  );

  return withGeneratedHash(
    [
      frontmatter(props),
      `# ${stats.label}`,
      '',
      GENERATED_BANNER,
      '',
      `${sorted.length} event(s) in this play session (started by ${group.startedBy}, ended by ${group.endedBy}; times in UTC).`,
      '',
      '| Time | Type | Who | What |',
      '| --- | --- | --- | --- |',
      ...rows,
      '',
      ...(changeLinks.length ? ['## Changes', '', ...changeLinks, ''] : []),
      ...(sessionNotes.length ? ['## Session notes', '', ...sessionNotes, ''] : []),
      ...renderSessionStatsSection(stats),
    ].join('\n')
  );
}

function tallyLine(tally: Tally): string {
  const entries = Object.entries(tally);
  if (entries.length === 0) return '(none)';
  return entries.map(([name, n]) => `${neutralizeTemplater(name)} ${n}`).join(', ');
}

function renderCombatStatsBlock(combat: CombatStats, index: number): string[] {
  return [
    `### Combat ${index + 1}${combat.sceneName ? ` (${neutralizeTemplater(combat.sceneName)})` : ''}`,
    '',
    `- Rounds: ${combat.rounds}`,
    `- Participants: ${combat.participants.length ? combat.participants.map(p => neutralizeTemplater(p)).join(', ') : '(none)'}`,
    `- Damage taken: ${tallyLine(combat.damageTaken)}`,
    `- Damage dealt: ${tallyLine(combat.damageDealt)}`,
    `- Healing: ${tallyLine(combat.healing)}`,
    `- Downs: ${combat.downs.length ? combat.downs.map(n => neutralizeTemplater(n)).join(', ') : '(none)'}`,
    `- Kills: ${combat.kills.length ? combat.kills.map(n => neutralizeTemplater(n)).join(', ') : '(none)'}`,
    `- Crits: ${combat.crits} · Fumbles: ${combat.fumbles}`,
    '',
  ];
}

/** The session note's "Stats" section (O3): a one-line summary plus one block
 * per combat (rounds, damage taken/dealt, downs, kills). */
function renderSessionStatsSection(stats: SessionStats): string[] {
  return [
    '## Stats',
    '',
    `${stats.rolls} roll(s), ${stats.crits} crit(s), ${stats.fumbles} fumble(s). Party: ` +
      `${stats.partyDamageDealt} damage dealt, ${stats.partyDamageTaken} damage taken, ` +
      `${stats.partyHealing} healing. ${stats.pcDowns} PC down(s), ${stats.npcKills} NPC kill(s).`,
    '',
    ...(stats.highestRoll
      ? [
          `Highest roll: ${stats.highestRoll.total}, ${neutralizeTemplater(stats.highestRoll.name)}` +
            `${stats.highestRoll.label ? ` (${neutralizeTemplater(stats.highestRoll.label)})` : ''}.`,
          '',
        ]
      : []),
    ...(stats.combats.length
      ? stats.combats.flatMap((c, i) => renderCombatStatsBlock(c, i))
      : ['(no combats this session)', '']),
  ];
}


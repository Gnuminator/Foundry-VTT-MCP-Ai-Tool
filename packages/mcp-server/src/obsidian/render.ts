export const GENERATED_BANNER =
  '> [!info] Generated by the Foundry AI Tool\n' +
  '> This note is rebuilt from the bridge vault on every export; edits here are lost. ' +
  'Write your own notes in `Prep/`.';

type PropValue = string | number | boolean | null | readonly string[];

function yamlScalar(value: string | number | boolean | null): string {
  if (value === null) return 'null';
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  // Quote everything textual: safe for colons, links, leading symbols, and
  // neutralized against Templater (the GM's vault runs that plugin).
  return JSON.stringify(neutralizeTemplater(value));
}

/** A YAML properties block (flat keys only, as Obsidian properties expect). */
export function frontmatter(props: Record<string, PropValue | undefined>): string {
  const lines = ['---'];
  for (const [key, value] of Object.entries(props)) {
    if (value === undefined) continue;
    if (Array.isArray(value)) {
      const list = value as readonly string[];
      if (list.length === 0) {
        lines.push(`${key}: []`);
      } else {
        lines.push(`${key}:`);
        for (const item of list) lines.push(`  - ${yamlScalar(item)}`);
      }
    } else {
      lines.push(`${key}: ${yamlScalar(value as string | number | boolean | null)}`);
    }
  }
  lines.push('---');
  return lines.join('\n');
}

/** The common properties every generated note carries, in a fixed order:
 * `type`, `fvtt_world`, the type's own properties, `fvtt_modified`,
 * `player_visible`, `schema`, `tags`, then the ownership marker (its hash is
 * a placeholder here; `withGeneratedHash` fills it in). `playerVisible` is
 * advisory for the GM only (docs/design/OBSIDIAN-O4-DESIGN.md section 4); every O2
 * note leaves it at the default `false`, so their text stays byte-identical. */
export function generatedProps(
  type: string,
  worldId: string,
  typeProps: Record<string, PropValue | undefined>,
  fvttModified: string | null,
  playerVisible = false
): Record<string, PropValue | undefined> {
  return {
    type,
    fvtt_world: worldId,
    ...typeProps,
    fvtt_modified: fvttModified,
    player_visible: playerVisible,
    schema: 1,
    tags: [`campaign/${worldId}`, type],
    generated_by: GENERATED_BY,
    generated_hash: '',
  };
}

/** Text safe inside a Markdown table cell, and neutralized against Templater. */
export function cell(value: unknown): string {
  const text =
    typeof value === 'string'
      ? value
      : typeof value === 'number' || typeof value === 'boolean'
        ? String(value)
        : '';
  // The backslash is escaped with the pipe: data ending in `\` must not turn `\|` into `\\|`,
  // an escaped backslash followed by a live column break.
  return neutralizeTemplater(text.replace(/\r?\n/g, ' ').replace(/[\\|]/g, '\\$&').trim());
}

/** A string safe as a file name on Windows, Linux and in Obsidian links. */
export function safeFileName(name: string): string {
  const printable = Array.from(name, ch => (ch.charCodeAt(0) < 32 ? ' ' : ch)).join('');
  const cleaned = printable
    .replace(/[<>:"/\\|?*#^[\]%]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[. ]+$/, '');
  const reserved = /^(con|prn|aux|nul|com\d|lpt\d)$/i;
  if (!cleaned || reserved.test(cleaned)) return `_${cleaned || 'untitled'}`;
  return cleaned.slice(0, 120);
}

function callout(type: string, title: string, body: string[], collapsed = true): string {
  const head = `> [!${type}]${collapsed ? '-' : ''} ${neutralizeTemplater(title)}`;
  const lines = body.length ? body : ['(empty)'];
  return [head, ...lines.map(l => (l ? `> ${neutralizeTemplater(l)}` : '>'))].join('\n');
}

/** "2026-09-28T09:52:27.308Z" -> "2026-09-28 09:52" (UTC, stable across hosts). */
function shortTime(iso: string | null | undefined): string {
  if (!iso) return '';
  return iso.replace('T', ' ').slice(0, 16);
}


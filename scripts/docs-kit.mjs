#!/usr/bin/env node
/**
 * Writes the scenario table and the counts in docs/dev/test-kit/scenarios.md from
 * scripts/test-kit/scenarios/ and the kit contract, the way `npm run docs:tools`
 * writes the tool reference. The generated block sits between two comment markers;
 * the rest of the page is hand-written.
 *
 *   node scripts/docs-kit.mjs           rewrite the block
 *   node scripts/docs-kit.mjs --check   exit 1 when the block is stale (CI, green)
 *   node scripts/docs-kit.mjs --root d  work on another tree (tests)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = 'docs/dev/test-kit/scenarios.md';
const START =
  '<!-- kit-scenarios:start (generated by scripts/docs-kit.mjs; edit the scenario file, not this block) -->';
const END = '<!-- kit-scenarios:end -->';

/** The generated block (markers included), built from the scenario files. */
export async function renderBlock(root = repoRoot) {
  const contract = await import(
    pathToFileURL(path.join(root, 'scripts/test-kit/lib/contract.mjs')).href
  );
  const { loadScenarios } = await import(
    pathToFileURL(path.join(root, 'scripts/test-kit/lib/loader.mjs')).href
  );
  const { scenarios, problems } = await loadScenarios([
    path.join(root, 'scripts/test-kit/scenarios'),
  ]);
  if (problems.length) throw new Error(`scenario problems:\n${problems.join('\n')}`);
  const list = scenarios.map(s => s.scenario).sort((a, b) => a.id.localeCompare(b.id));
  const sizes = contract.KIT_SIZES;
  const count = size => list.filter(s => s.sizes.includes(size)).length;
  const worlds = contract.KIT_WORLDS;
  const esc = s => s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
  const body = list.map(s => [
    `\`${s.id}\``,
    sizes.filter(z => s.sizes.includes(z)).join(', '),
    s.tags.join(', '),
    `${esc(s.title)}${s.licensed ? ' (licensed)' : ''}`,
  ]);
  const head = ['Id', 'Sizes', 'Tags', 'What it proves'];
  const widths = head.map((h, i) => Math.max(h.length, ...body.map(r => r[i].length)));
  const row = cells => `| ${cells.map((c, i) => c.padEnd(widths[i])).join(' | ')} |`;
  const lines = [
    START,
    '',
    `${list.length} scenarios ship in the repo (${sizes.map(z => `${count(z)} in \`${z}\``).join(', ')}). ` +
      `The kit builds and writes only in its ${worlds.length} kit worlds: ${worlds.map(w => `\`${w}\``).join(', ')}.`,
    '',
    row(head),
    `| ${widths.map(w => '-'.repeat(w)).join(' | ')} |`,
    ...body.map(row),
    '',
    END,
  ];
  return lines.join('\n');
}

export function replaceBlock(page, block) {
  const a = page.indexOf('<!-- kit-scenarios:start');
  const b = page.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${PAGE} has no kit-scenarios markers`);
  return page.slice(0, a) + block + page.slice(b + END.length);
}

async function main() {
  const check = process.argv.includes('--check');
  const rootArg = process.argv.indexOf('--root');
  const root = rootArg > -1 ? path.resolve(process.argv[rootArg + 1]) : repoRoot;
  const file = path.join(root, PAGE);
  if (!existsSync(file)) throw new Error(`${PAGE} not found`);
  const page = readFileSync(file, 'utf8');
  const next = replaceBlock(page, await renderBlock(root));
  if (next === page) {
    console.log('docs-kit: scenarios.md scenario table is current');
    return;
  }
  if (check) {
    console.error(
      'docs-kit: the scenario table in docs/dev/test-kit/scenarios.md is stale. Run `npm run docs:kit` and commit the result.'
    );
    process.exit(1);
  }
  writeFileSync(file, next);
  console.log('docs-kit: rewrote the scenario table in docs/dev/test-kit/scenarios.md');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(e => {
    console.error(e instanceof Error ? e.message : String(e));
    process.exit(1);
  });
}

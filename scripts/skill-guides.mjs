#!/usr/bin/env node
/**
 * Generate packages/mcp-server/src/skill-guides.generated.ts: the full content of the three skills
 * (GM coach, D&D helper, D&D helper player edition) as one embedded bundle, served by the tools
 * `get-skill-guide` and `get-player-skill-guide`. The uploaded skills are thin stubs
 * (the stub folders under tools), so the pages change with a backend deploy, not a re-upload.
 *
 * Sources are the same functions that build the full zips (`collectFiles`, `collectPlayerFiles`),
 * so there is one place that decides what each skill holds. Embedded in the module (not read from
 * disk at run time) so the esbuild bundle of the installer and the Pi image both carry it.
 *
 *   node scripts/skill-guides.mjs            write the file; a missing source warns and writes an
 *                                            empty bundle (npm ci before the sources are copied)
 *   node scripts/skill-guides.mjs --require  a missing source or an empty bundle fails (builds)
 *
 * The output is gitignored. No campaign or book text: the sources are public docs, the Foundry UI
 * reference pages and the skills' own working pages.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..');
export const OUT_FILE = path.join(
  repo,
  'packages',
  'mcp-server',
  'src',
  'skill-guides.generated.ts'
);

/**
 * @returns {Promise<Record<string, Record<string, string>>>}
 */
export async function collectGuides() {
  const coach = await import('../tools/gm-coach/build.mjs');
  const helper = await import('../tools/dnd-helper/build.mjs');
  return {
    'gm-coach': Object.fromEntries(coach.collectFiles()),
    'dnd-helper': Object.fromEntries(helper.collectFiles()),
    'dnd-helper-player': Object.fromEntries(helper.collectPlayerFiles()),
  };
}

/** The TypeScript source for a bundle. */
export function render(guides) {
  return `// Generated by scripts/skill-guides.mjs (mcp-server build, npm ci); not committed.
export const SKILL_GUIDES: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(guides, null, 1)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const require = process.argv.includes('--require');
  let guides = {};
  try {
    guides = await collectGuides();
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (require) {
      console.error(`skill-guides: cannot read the skill sources (${message})`);
      process.exit(1);
    }
    console.warn(`skill-guides: sources not found, writing an empty bundle (${message})`);
  }
  if (require && !Object.values(guides).every(files => Object.keys(files).length > 3)) {
    console.error('skill-guides: a skill came out nearly empty');
    process.exit(1);
  }
  mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, render(guides));
  const pages = Object.values(guides).reduce((n, f) => n + Object.keys(f).length, 0);
  console.log(`skill-guides: ${Object.keys(guides).length} skills, ${pages} pages`);
}
